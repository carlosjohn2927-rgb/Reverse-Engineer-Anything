/** Tool name -> family id, built once from the membership lists above. */
const FAMILY_BY_TOOL = new Map(
  FAMILIES.flatMap((family) => family.tools.map((name) => [name, family.id])),
);

/** Family id for a tool; `other` only if the tool is not in any list. */
export const familyOf = (toolName) => FAMILY_BY_TOOL.get(toolName) ?? "other";

/** Every tool name the UI claims to place in a family. */
export const classifiedToolNames = () => [...FAMILY_BY_TOOL.keys()];
